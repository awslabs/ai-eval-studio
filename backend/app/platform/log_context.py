"""Logging filter that injects per-request correlation IDs.

Every authenticated request runs through ``auth_middleware`` which sets
:data:`app.platform.types.request_context` to a
:class:`RequestContextValue` carrying ``request_id``, ``user_id``, and
optionally ``project_id`` / ``turn_id`` / ``job_id``. Those IDs are
exactly what an operator needs to correlate a CloudWatch log line back
to a specific user action.

The filter pulls the ContextVar on every record emit and attaches the
fields as record attributes (``record.request_id`` etc.). The formatter
in ``app.main`` references them via ``%(request_id)s``-style tokens, so
existing ``logger.info("...")`` call sites pick up correlation without
needing ``extra=`` plumbing. Background-task code paths (no request
context) get empty strings, which render as ``-`` placeholders.

Why a Filter, not a LoggerAdapter:
- A Filter lives once on the handler and applies to every logger that
  feeds that handler. A LoggerAdapter would have to wrap every
  ``getLogger`` site — there are dozens.
- The filter is read-only relative to the record's level/message, so
  it can't accidentally suppress a log line; ``filter()`` returns
  ``True`` unconditionally.
"""
from __future__ import annotations

import logging

from app.platform.types import request_context


class RequestContextFilter(logging.Filter):
    """Attach request-context fields to every log record.

    Attributes injected (always present, empty string when not set):
        record.request_id: UUID generated by ``auth_middleware``.
        record.user_id: Cognito ``sub`` (cloud) or ``LOCAL_DEV_USER_ID``.
        record.project_id: Set when an MCP tool / route binds a project.
        record.turn_id: Set inside an agent-turn execution scope.
        record.job_id: Set inside a job-execution scope.
    """

    _PLACEHOLDER = "-"

    def filter(self, record: logging.LogRecord) -> bool:
        ctx = request_context.get()
        if ctx is None:
            record.request_id = self._PLACEHOLDER
            record.user_id = self._PLACEHOLDER
            record.project_id = self._PLACEHOLDER
            record.turn_id = self._PLACEHOLDER
            record.job_id = self._PLACEHOLDER
        else:
            # Use only the first 8 chars of long IDs for log readability.
            # The full IDs are still queryable via Cognito / DDB if a
            # responder needs them; a CloudWatch log column with full
            # 36-char UUIDs is unreadable.
            record.request_id = ctx.request_id[:8] if ctx.request_id else self._PLACEHOLDER
            record.user_id = ctx.user_id[:8] if ctx.user_id else self._PLACEHOLDER
            record.project_id = (
                ctx.project_id[:8] if ctx.project_id else self._PLACEHOLDER
            )
            record.turn_id = (
                ctx.turn_id[:8] if ctx.turn_id else self._PLACEHOLDER
            )
            record.job_id = (
                ctx.job_id[:8] if ctx.job_id else self._PLACEHOLDER
            )
        return True


__all__ = ["RequestContextFilter"]
