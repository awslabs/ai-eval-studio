/**
 * Resolve a theme + mode into the flat CSS-variable map the app applies
 * to ``:root`` (base ``theme`` values overlaid with the mode-specific
 * ``light``/``dark`` overrides), filtered to the known {@link THEME_VARS}.
 *
 * This is the single source of truth for "what variables does this theme
 * produce" — {@link applyTheme} uses it to style the live app.
 *
 * @param themeId - Theme id (falls back to {@link DEFAULT_THEME} if unknown).
 * @param mode - "light" or "dark".
 * @returns Map of CSS var name (no leading ``--``) to value.
 */
export function resolveThemeVars(
  themeId: string,
  mode: "light" | "dark",
): Record<string, string> {
  const def = themes[themeId] ?? themes[DEFAULT_THEME];
  const merged = { ...def.theme, ...(mode === "dark" ? def.dark : def.light) };
  const allowed = new Set<string>(THEME_VARS);
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(merged)) {
    if (allowed.has(key)) out[key] = value;
  }
  return out;
}
